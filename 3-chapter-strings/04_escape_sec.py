
# \n - New line
print("Hello\nWorld")

# \t - Tab space
print("Hello\tWorld")

# \\ - Backslash
print("C:\\Users\\Dell")

# \' - Single quote
print('It\'s Python')

# \" - Double quote
print("He said, \"Hello!\"")

# \b - Backspace
print("Helloo\b")

# \r - Carriage return
print("Hello\rWorld")

# \f - Form feed
print("Hello\fWorld")

# \v - Vertical tab
print("Hello\vWorld")

# \a - Alert character
print("\a")

# \0 - Null character
print("Hello\0World")
