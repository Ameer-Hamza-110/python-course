# String Data Type
# A string is a sequence of characters. In Python, strings are enclosed in either single quotes
name = 'John Doe'  # Using single quotes
greeting = "Hello, World!"  # Using double quotes

# Number Data Type
# Python has two main numeric types: integers and floating-point numbers.
age = 25  # Integer
height = 5.9  # Floating-point number

# Boolean Data Type
# A boolean represents one of two values: True or False.
is_student = True  # Boolean value

# None Data Type
# The None type represents the absence of a value or a null value.
middle_name = None  # None value